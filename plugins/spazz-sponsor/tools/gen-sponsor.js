// node tools/gen-sponsor.js  ->  spazz-sponsor-spec.h
const fs = require('fs');
const path = require('path');
const { LISTS, PRESETS } = require('./sponsor-spec.js');

/* page config key -> source setting key and kind */
const KEYS = {
  style: ['style', 'str'], enter: ['enter', 'str'], exit: ['exit', 'str'], textAnim: ['text_anim', 'str'],
  imageAnim: ['image_anim', 'str'], idle: ['idle', 'str'], anchor: ['anchor', 'str'], font: ['font', 'str'],
  accent: ['accent', 'color'], accent2: ['accent2', 'color'], text: ['text_color', 'color'], bg: ['bg_color', 'color'],
  bgOpacity: ['bg_opacity', 'num'], size: ['size', 'num'], marginX: ['margin_x', 'int'], marginY: ['margin_y', 'int'],
};

function cs(s) {
  let o = '"';
  for (const b of Buffer.from(String(s), 'utf8')) {
    if (b === 34) o += '\\"'; else if (b === 92) o += '\\\\';
    else if (b < 32 || b > 126) o += '\\' + b.toString(8).padStart(3, '0');
    else o += String.fromCharCode(b);
  }
  return o + '"';
}
const num = (v) => { const s = String(+v); return /[.e]/.test(s) ? s : s + '.0'; };

let h = `/* Generated by tools/gen-sponsor.js from tools/sponsor-spec.js - edit those instead. */
#pragma once

struct spn_option {
\tconst char *value;
\tconst char *label;
};

enum spn_kind { SPN_STR, SPN_COLOR, SPN_NUM, SPN_INT };

struct spn_preset_val {
\tconst char *key;
\tenum spn_kind kind;
\tconst char *str;
\tdouble num; /* colours: 0xRRGGBB */
};

struct spn_preset {
\tconst char *name;
\tconst struct spn_preset_val *vals;
\tint count;
};

`;
for (const [name, list] of Object.entries(LISTS)) {
  h += `static const struct spn_option spn_${name}[] = {\n${list.map(([v, l]) => `\t{${cs(v)}, ${cs(l)}},`).join('\n')}\n\t{NULL, NULL}};\n`;
}
h += '\n';
PRESETS.forEach((pr, i) => {
  const vals = Object.entries(pr.p).map(([k, v]) => {
    const m = KEYS[k];
    if (!m) throw new Error(`preset ${pr.name}: unknown key ${k}`);
    const [key, kind] = m;
    if (kind === 'str') {
      const list = LISTS[k];
      if (list && !list.some(([val]) => val === v)) throw new Error(`preset ${pr.name}: ${k}=${v} not in list`);
      return `{${cs(key)}, SPN_STR, ${cs(v)}, 0.0}`;
    }
    if (kind === 'color') return `{${cs(key)}, SPN_COLOR, NULL, 0x${v.slice(1).toLowerCase()}}`;
    return `{${cs(key)}, ${kind === 'int' ? 'SPN_INT' : 'SPN_NUM'}, NULL, ${num(v)}}`;
  });
  h += `static const struct spn_preset_val spn_preset_${i}[] = {\n\t${vals.join(',\n\t')}};\n`;
});
h += `\nstatic const struct spn_preset spn_presets[] = {\n`;
PRESETS.forEach((pr, i) => { h += `\t{${cs(pr.name)}, spn_preset_${i}, ${Object.keys(pr.p).length}},\n`; });
h += `};\n#define SPN_PRESET_COUNT ((int)(sizeof(spn_presets) / sizeof(spn_presets[0])))\n`;

const out = path.join(__dirname, '..', 'spazz-sponsor-spec.h');
fs.writeFileSync(out, h);
console.log(`${Object.keys(LISTS).length} lists, ${PRESETS.length} presets -> ${out}`);
