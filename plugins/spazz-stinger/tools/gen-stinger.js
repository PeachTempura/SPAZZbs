// node tools/gen-stinger.js  ->  spazz-stinger-spec.h
const fs = require('fs');
const path = require('path');
const { STYLES, PRESETS } = require('./stinger-spec.js');

function cs(s) {
  let o = '"';
  for (const b of Buffer.from(String(s), 'utf8')) {
    if (b === 34) o += '\\"';
    else if (b === 92) o += '\\\\';
    else if (b < 32 || b > 126) o += '\\' + b.toString(8).padStart(3, '0');
    else o += String.fromCharCode(b);
  }
  return o + '"';
}
const num = (v) => { const s = String(+v); return /[.e]/.test(s) ? s : s + '.0'; };
const hex = (h) => '0x' + h.slice(1).toLowerCase();
const TYPE = { slider: 'STG_SLIDER', color: 'STG_COLOR', toggle: 'STG_TOGGLE', select: 'STG_SELECT' };
const SLOT = { c1: 0, c2: 1, c3: 2, c4: 3, p1: 4, p2: 5, p3: 6, p4: 7, p5: 8, p6: 9, p7: 10, p8: 11 };

const params = [];
STYLES.forEach((s, si) => s.params.forEach((p) => params.push({ ...p, style: si })));

let h = `/* Generated by tools/gen-stinger.js from tools/stinger-spec.js - edit those instead. */
#pragma once

enum stg_type { STG_SLIDER, STG_COLOR, STG_TOGGLE, STG_SELECT };

struct stg_style {
\tconst char *id;
\tconst char *name;
\tconst char *technique;
};

struct stg_option {
\tint value;
\tconst char *label;
};

struct stg_param {
\tconst char *key;
\tconst char *label;
\tconst char *tip;
\tenum stg_type type;
\tint style;
\tint slot; /* 0-3 colours c1-c4, 4-11 numbers p1-p8 */
\tdouble min, max, step, def; /* colours: def is 0xRRGGBB */
\tconst struct stg_option *options;
\tint option_count;
};

static const struct stg_style stg_styles[] = {
${STYLES.map((s) => `\t{${cs(s.id)}, ${cs(s.name)}, ${cs(s.tech)}},`).join('\n')}
};
#define STG_STYLE_COUNT ((int)(sizeof(stg_styles) / sizeof(stg_styles[0])))

`;
for (const p of params) if (p.type === 'select')
  h += `static const struct stg_option stg_opts_${p.key}[] = {${p.options.map(([v, l]) => `{${v}, ${cs(l)}}`).join(', ')}};\n`;

h += `\nstatic const struct stg_param stg_params[] = {\n`;
for (const p of params) {
  const def = p.type === 'color' ? hex(p.def) : p.type === 'toggle' ? (p.def ? '1.0' : '0.0') : num(p.def);
  h += `\t{${cs(p.key)}, ${cs(p.label)}, ${p.tip ? cs(p.tip) : 'NULL'}, ${TYPE[p.type]}, ${p.style}, ${SLOT[p.slot]}, ` +
    `${num(p.min ?? 0)}, ${num(p.max ?? 0)}, ${num(p.step ?? 0)}, ${def}, ` +
    `${p.type === 'select' ? 'stg_opts_' + p.key : 'NULL'}, ${p.type === 'select' ? p.options.length : 0}},\n`;
}
h += `};\n#define STG_PARAM_COUNT ((int)(sizeof(stg_params) / sizeof(stg_params[0])))\n\n`;

h += `struct stg_preset_val {
\tconst char *key;
\tdouble value; /* colours: 0xRRGGBB */
};

struct stg_preset {
\tconst char *name;
\tconst char *style;
\tint duration_ms;
\tint cut_percent;
\tconst struct stg_preset_val *vals;
\tint count;
};

`;
PRESETS.forEach((pr, i) => {
  const style = STYLES.find((s) => s.id === pr.style);
  if (PRESETS.filter((q) => q.name === pr.name).length > 1) throw new Error('duplicate preset ' + pr.name);
  if (!style) throw new Error('unknown style ' + pr.style);
  const vals = Object.entries(pr.p).map(([k, v]) => {
    const def = style.params.find((p) => p.key === k);
    if (!def) throw new Error(`preset ${pr.name}: ${k} is not a ${pr.style} setting`);
    const value = def.type === 'color' ? hex(v) : def.type === 'toggle' ? (v ? '1.0' : '0.0') : num(v);
    return `{${cs(k)}, ${value}}`;
  });
  h += vals.length
    ? `static const struct stg_preset_val stg_preset_${i}[] = {${vals.join(', ')}};\n`
    : `static const struct stg_preset_val stg_preset_${i}[] = {{NULL, 0.0}};\n`;
});
h += `\nstatic const struct stg_preset stg_presets[] = {\n`;
PRESETS.forEach((pr, i) => {
  h += `\t{${cs(pr.name)}, ${cs(pr.style)}, ${pr.duration}, ${pr.cut}, stg_preset_${i}, ${Object.keys(pr.p).length}},\n`;
});
h += `};\n#define STG_PRESET_COUNT ((int)(sizeof(stg_presets) / sizeof(stg_presets[0])))\n`;

const out = path.join(__dirname, '..', 'spazz-stinger-spec.h');
fs.writeFileSync(out, h);
console.log(`${STYLES.length} styles, ${params.length} settings, ${PRESETS.length} presets -> ${out}`);
