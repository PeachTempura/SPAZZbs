// node tools/gen-text.js  ->  spazz-text-spec.h and data/text/fonts.css
const fs = require('fs');
const path = require('path');
const { KEYS, FONTS, LISTS, PRESETS } = require('./text-spec.js');

/* a preset sets the look and the motion; these stay yours (a preset may still
 * suggest one, e.g. a sound to react to, if you haven't chosen it yourself) */
const KEEP = new Set(['source', 'text', 'npFormat', 'npHide', 'clock', 'cdKind', 'cdMin', 'cdTime', 'cdDone', 'alignH',
  'alignV', 'margin', 'wrap', 'size', 'replayOnShow', 'cycle', 'showSec', 'hideSec', 'react', 'reactSens', 'reactSmooth']);

function cs(s) {
  let o = '"';
  for (const b of Buffer.from(String(s), 'utf8')) {
    if (b === 34) o += '\\"'; else if (b === 92) o += '\\\\';
    else if (b < 32 || b > 126) o += '\\' + b.toString(8).padStart(3, '0');
    else o += String.fromCharCode(b);
  }
  return o + '"';
}
const num = (v) => { const s = String(+v); return /[.e]/.test(s) ? s : s + '.0'; };
const KIND = { str: 'STX_STR', color: 'STX_COLOR', num: 'STX_NUM', int: 'STX_INT', bool: 'STX_BOOL' };
const hex = (c) => { if (!/^#[0-9a-f]{6}$/i.test(c)) throw new Error(`bad colour ${c}`); return parseInt(c.slice(1), 16); };
function val(kind, v) {
  if (kind === 'str') return `${cs(v)}, 0.0`;
  if (kind === 'color') return `NULL, ${num(hex(v))}`;
  if (kind === 'bool') return `NULL, ${v ? '1.0' : '0.0'}`;
  return `NULL, ${num(v)}`;
}

let h = `/* Generated by tools/gen-text.js from tools/text-spec.js - edit those instead. */
#pragma once

struct stx_option {
\tconst char *value;
\tconst char *label;
};

enum stx_kind { STX_STR, STX_COLOR, STX_NUM, STX_INT, STX_BOOL };

/* a setting, its name on the page, and its default */
struct stx_key {
\tconst char *setting;
\tconst char *page;
\tenum stx_kind kind;
\tconst char *str;
\tdouble num; /* colours: 0xRRGGBB */
\tbool preset; /* a preset resets it */
};

struct stx_preset_val {
\tconst char *key;
\tenum stx_kind kind;
\tconst char *str;
\tdouble num;
};

struct stx_preset {
\tconst char *name;
\tconst struct stx_preset_val *vals;
\tint count;
};

`;
for (const [name, list] of Object.entries(LISTS)) {
  h += `static const struct stx_option stx_${name}[] = {\n${list.map(([v, l]) => `\t{${cs(v)}, ${cs(l)}},`).join('\n')}\n\t{NULL, NULL}};\n`;
}
h += `\nstatic const struct stx_key stx_keys[] = {\n`;
for (const [page, [setting, kind, def]] of Object.entries(KEYS)) {
  h += `\t{${cs(setting)}, ${cs(page)}, ${KIND[kind]}, ${val(kind, def)}, ${KEEP.has(page) ? 'false' : 'true'}},\n`;
}
h += `\t{NULL, NULL, STX_STR, NULL, 0.0, false}};\n\n`;

const names = new Set();
PRESETS.forEach((pr, i) => {
  if (names.has(pr.name)) throw new Error(`duplicate preset ${pr.name}`);
  names.add(pr.name);
  const vals = Object.entries(pr.p).map(([k, v]) => {
    if (!KEYS[k]) throw new Error(`preset ${pr.name}: unknown key ${k}`);
    const [key, kind] = KEYS[k];
    const list = LISTS[k];
    if (list && !list.some(([id]) => id === v)) throw new Error(`preset ${pr.name}: ${k}=${v} isn't in the list`);
    return `\t{${cs(key)}, ${KIND[kind]}, ${val(kind, v)}},`;
  });
  h += `static const struct stx_preset_val stx_preset_${i}[] = {\n${vals.join('\n')}\n};\n`;
});
h += `\nstatic const struct stx_preset stx_presets[] = {\n${PRESETS.map((pr, i) => `\t{${cs(pr.name)}, stx_preset_${i}, ${Object.keys(pr.p).length}},`).join('\n')}\n};\n`;
h += `#define STX_PRESET_COUNT ${PRESETS.length}\n`;
fs.writeFileSync(path.join(__dirname, '..', 'spazz-text-spec.h'), h);

let css = '/* Generated by tools/gen-text.js - the fonts SPAZZ Text bundles (all OFL / Apache, licences alongside) */\n';
for (const [id, , files] of FONTS) {
  if (!files) continue;
  for (const [file, weight] of files) {
    if (!fs.existsSync(path.join(__dirname, '..', 'data', 'text', 'fonts', file))) throw new Error(`missing ${file}`);
    css += `@font-face { font-family: '${id}'; src: url('fonts/${file}') format('truetype'); font-weight: ${weight}; font-display: block; }\n`;
  }
}
fs.writeFileSync(path.join(__dirname, '..', 'data', 'text', 'fonts.css'), css);
console.log(`${PRESETS.length} presets, ${Object.keys(KEYS).length} keys, ${FONTS.length} fonts`);
