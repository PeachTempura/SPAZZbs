#!/usr/bin/env node
/* SPAZZbs visualizer packs: builds data/pack-<name>.effect from
 * packs/common.fxh + packs/<name>.fx, and checks that each pack's style
 * table (pack-<name>.h), its techniques and its locale lines agree.
 *
 *   node tools/gen-packs.js          write the effects
 *   node tools/gen-packs.js --check  fail if a generated effect is stale
 *
 * See tools/PACKS.md. */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PACKS = ['retro', 'feedback', 'modern'];
const FLAGS = ['VZ_AMOUNT', 'VZ_SPEED', 'VZ_CMOTION', 'VZ_FEEDBACK', 'VZ_CALM'];
const check = process.argv.includes('--check');

const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const errors = [];
const fail = (msg) => errors.push(msg);

/* the built-in styles: spazz-visualizer.c's style_techniques[] */
const csrc = read('spazz-visualizer.c');
const arr = csrc.match(/static const char \*style_techniques\[\] = \{([\s\S]*?)\};/);
if (!arr) {
	console.error('gen-packs: could not find style_techniques[] in spazz-visualizer.c');
	process.exit(1);
}
const mainStyles = [...arr[1].replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/"([^"]+)"/g)].map((m) => m[1]);
const keys = new Map(mainStyles.map((k) => [k, 'spazz-visualizer.c']));
const techs = new Map(mainStyles.map((k) => [k, 'spazz-visualizer.effect']));
techs.set('FeedbackShow', 'common.fxh');

const common = read('packs/common.fxh');
let stale = 0;
let total = 0;

for (const name of PACKS) {
	const fx = read(`packs/${name}.fx`);
	const table = read(`pack-${name}.h`);
	const locale = fs.existsSync(path.join(ROOT, `packs/locale/pack-${name}.ini.part`))
		? read(`packs/locale/pack-${name}.ini.part`)
		: '';

	const fxTechs = [...fx.matchAll(/^technique\s+([A-Za-z_][A-Za-z0-9_]*)/gm)].map((m) => m[1]);
	const rows = [...table.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/PACK_STYLE\(\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,\s*([^)]*)\)/g)].map(
		(m) => ({key: m[1], tech: m[2], flags: m[3].trim()}));
	const labels = new Set([...locale.matchAll(/^Style\.([^=\s]+)\s*=\s*".+"\s*$/gm)].map((m) => m[1]));

	for (const t of fxTechs) {
		if (techs.has(t)) {
			fail(`${name}: technique "${t}" is also in ${techs.get(t)} (technique names must be unique)`);
		}
		techs.set(t, `packs/${name}.fx`);
		if (!rows.some((r) => r.tech === t)) {
			fail(`${name}: technique "${t}" has no row in pack-${name}.h`);
		}
	}
	for (const r of rows) {
		total++;
		if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(r.key)) {
			fail(`${name}: key "${r.key}" must be letters/digits/_ (it's a setting value and locale key)`);
		}
		if (keys.has(r.key)) {
			fail(`${name}: key "${r.key}" is also used by ${keys.get(r.key)}`);
		}
		keys.set(r.key, `pack-${name}.h`);
		if (!fxTechs.includes(r.tech)) {
			fail(`${name}: "${r.key}" names technique "${r.tech}", which packs/${name}.fx doesn't have`);
		}
		if (!labels.has(r.key)) {
			fail(`${name}: no label for "${r.key}": add Style.${r.key}="..." to packs/locale/pack-${name}.ini.part`);
		}
		if (r.flags !== '0') {
			for (const f of r.flags.split('|').map((s) => s.trim())) {
				if (!FLAGS.includes(f)) {
					fail(`${name}: "${r.key}" has unknown flag "${f}" (use ${FLAGS.join(' ')} or 0)`);
				}
			}
		}
		/* feedback styles read last frame; anything else must not need it */
		const body = fx.match(new RegExp(`technique\\s+${r.tech}\\s*\\{[\\s\\S]*?pixel_shader\\s*=\\s*(\\w+)`));
		if (body) {
			const fn = body[1];
			const fnSrc = fx.match(new RegExp(`float4 ${fn}\\(VertData v_in\\) : TARGET\\s*\\{[\\s\\S]*?\\n\\}`));
			const usesPrev = fnSrc && /\bprev_at\(|\bprev\.Sample|\bprev_on\b/.test(fnSrc[0]);
			const isFb = r.flags.includes('VZ_FEEDBACK');
			if (usesPrev && !isFb) {
				fail(`${name}: "${r.key}" reads last frame (prev) but isn't flagged VZ_FEEDBACK`);
			}
			if (isFb && fnSrc && !/\bfb_out\(/.test(fnSrc[0])) {
				fail(`${name}: feedback style "${r.key}" should return fb_out(...) (ungraded, no backdrop)`);
			}
		}
	}
	for (const k of labels) {
		if (!rows.some((r) => r.key === k)) {
			fail(`${name}: packs/locale/pack-${name}.ini.part has Style.${k} but no such style`);
		}
	}

	const out = `// GENERATED by tools/gen-packs.js from packs/common.fxh + packs/${name}.fx.\n` +
		    `// Do not edit: edit those and run  node tools/gen-packs.js\n\n` + common + '\n' + fx;
	const dest = path.join(ROOT, `data/pack-${name}.effect`);
	const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : null;
	if (cur !== out) {
		if (check) {
			fail(`data/pack-${name}.effect is out of date: run node tools/gen-packs.js`);
			stale++;
		} else {
			fs.writeFileSync(dest, out);
		}
	}
}

if (errors.length) {
	for (const e of errors) {
		console.error('gen-packs: ' + e);
	}
	process.exit(1);
}
console.log(`gen-packs: ${PACKS.length} packs, ${total} styles (+${mainStyles.length} built in)` +
	    (check ? ', generated effects up to date' : ', effects written'));
